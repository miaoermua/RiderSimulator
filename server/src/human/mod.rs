//! 真人玩家层：**只回答「谁是真人，谁来操作他」**。
//!
//! ```text
//! human/   真人身份与 AI 让位判定   ← 依赖 sim；sim 不依赖它（单向）
//! ```
//!
//! ## 为什么单独一层
//!
//! `sim/` 是**世界本身**：订单、骑手、调度、经济。这些规则对真人和模拟骑手
//! 一视同仁，不需要知道后面坐的是人还是 AI。少数确实需要知道「谁是真人」的判定
//! 集中在 `human/`，`sim/` 只收结论（[`crate::sim::tick::TickInput`]）。
//!
//! ## 依赖方向
//!
//! `human → sim`，**反过来不允许**：`sim/` 不许出现 `crate::human`。
//! `sim/` 是「被所有上层依赖、自己不依赖任何东西」的一层，破掉就是分层失效。
//! 这条约束有源码级断言兜着（见 `server/tests/layering.rs`）。
//!
//! ## 这一层会长大
//!
//! 真人的玩法会持续分化——例如「出餐慢可以上报」这类**只有真人做得出的动作**。
//! 分化都长在这一层，`sim/` 的规则和单测不受影响。

